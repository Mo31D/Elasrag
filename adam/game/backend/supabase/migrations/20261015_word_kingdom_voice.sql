 requested_by uuid not null references public.ala_parents(user_id),
 status text not null default 'reserved' check(status in ('reserved','pending','approved','failed')),
 provider_model text not null default 'gemini-3.8-flash-tts',
 storage_path text,
 failure_code text,
 created_at timestamptz not null default now(),
 completed_at timestamptz,
 approved_at timestamptz,
 primary key(word_id,variant)
);
