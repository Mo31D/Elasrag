create or replace function public.ala_reserve_word_voice(p_parent uuid,p_word text,p_variant text)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare cfg public.ala_settings; existing public.ala_word_voice_jobs; v text;
begin
 perform pg_advisory_xact_lock(hashtextextended(p_parent::text,2026));
 perform pg_advisory_xact_lock(hashtextextended(p_word||':'||p_variant,2027));
 if p_variant not in ('word','sentence') then raise exception 'invalid variant'; end if;
 if not exists(select 1 from public.ala_word_lexicon where id=p_word) then raise exception 'unknown word'; end if;
 if not exists(select 1 from public.ala_parents where user_id=p_parent and active) then raise exception 'parent not authorised'; end if;
 select * into existing from public.ala_word_voice_jobs where word_id=p_word and variant=p_variant;
 if found then return jsonb_build_object('reused',true,'status',existing.status,'path',existing.storage_path); end if;
 select * into cfg from public.ala_settings where parent_id=p_parent;
 if not found or not cfg.free_tier_confirmed or cfg.paid_usage_allowed then raise exception 'free tier not confirmed'; end if;
